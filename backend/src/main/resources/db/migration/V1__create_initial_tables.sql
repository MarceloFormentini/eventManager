
CREATE TABLE type_institution (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE institution (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_institution_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_institution_type
        FOREIGN KEY (type_institution_id)
        REFERENCES type_institution (id)
        ON DELETE RESTRICT
);

CREATE TABLE location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_location_institution
        FOREIGN KEY (institution_id)
        REFERENCES institution (id)
        ON DELETE RESTRICT
);

CREATE TABLE event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    start_date TIMESTAMPTZ NOT NULL,
    end_date TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_event_location
        FOREIGN KEY (location_id)
        REFERENCES location (id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_event_dates
        CHECK (end_date >= start_date),

    CONSTRAINT chk_event_status
        CHECK (status IN (
            'DRAFT',
            'PUBLISHED',
            'CANCELLED',
            'COMPLETED'
        ))
);


CREATE TABLE outbox_event (
    id UUID PRIMARY KEY,

    aggregate_type VARCHAR(100) NOT NULL,
    aggregate_id BIGINT NOT NULL,

    event_type VARCHAR(150) NOT NULL,
    payload TEXT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    last_error TEXT,

    CONSTRAINT ck_outbox_event_status
        CHECK (status IN ('PENDING', 'PUBLISHED', 'FAILED')),

    CONSTRAINT ck_outbox_event_attempts
        CHECK (attempts >= 0)
);

CREATE INDEX idx_institution_type
    ON institution (type_institution_id);

CREATE INDEX idx_location_institution
    ON location (institution_id);

CREATE INDEX idx_event_location
    ON event (location_id);

CREATE INDEX idx_event_start_date
    ON event (start_date);

CREATE INDEX idx_event_status
    ON event(status);

CREATE INDEX idx_outbox_event_pending
    ON outbox_event (status, next_attempt_at, created_at);

CREATE INDEX idx_outbox_event_aggregate
    ON outbox_event (aggregate_type, aggregate_id);